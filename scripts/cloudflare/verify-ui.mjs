import {qaSession} from './qa-session.mjs';
import { chromium } from 'playwright';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const privateDir = new URL('../../.migration-backups/', import.meta.url);
const session = await qaSession();
const snapshot = JSON.parse(await readFile(new URL('source-snapshot.json', privateDir)));
const manifest = JSON.parse(await readFile(new URL('image-manifest.json', privateDir)));
const browser = await chromium.launch({ headless: true });
const errors = [], externalRequests = [], failures = [];
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, timezoneId: 'Asia/Tokyo' });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.name));
page.on('request', request => { if (!request.url().startsWith(session.base) && !/^(data|blob):/.test(request.url())) externalRequests.push(new URL(request.url()).origin); });
page.on('response', response => { if (response.status() >= 400) failures.push({ status: response.status(), path: new URL(response.url()).pathname }); });
await page.goto(session.base+'/');
await page.getByText('気になったら、即メモ').waitFor();
await page.screenshot({path:new URL('full-landing.png',privateDir).pathname,fullPage:true,animations:'disabled'});
await page.goto(session.base+'/auth');
await page.getByRole('button',{name:'Googleでログイン'}).waitFor();
await page.screenshot({path:new URL('full-auth.png',privateDir).pathname,fullPage:true,animations:'disabled'});
await page.goto(session.base + '/dashboard');
assert.equal(new URL(page.url()).pathname, '/auth');
const eq=session.cookie.indexOf('=');
await context.addCookies([{name:session.cookie.slice(0,eq),value:session.cookie.slice(eq+1),url:session.base,httpOnly:true,secure:true,sameSite:'Lax'}]);
await page.goto(session.base+'/dashboard');
await page.waitForURL('**/dashboard');
await page.getByPlaceholder('今、思い出したことを書く…').waitFor();
await page.screenshot({ path: new URL('dashboard-desktop.png', privateDir).pathname, fullPage: true, animations: 'disabled' });
const firstImage = manifest.find(i => i.mime === 'image/jpeg' || i.mime === 'image/png');
const block = snapshot.blocks.find(b => (b.images || []).includes(firstImage.old_url));
const date = new Date(Date.parse(block.occurred_at) + 5 * 3600000).toISOString().slice(0,10);
await page.goto(session.base + '/dashboard?date=' + date);
const image = page.locator('img[src*="/media/block-images/"]').first();
await image.waitFor();
await image.scrollIntoViewIfNeeded();
await page.waitForFunction(() => [...document.images].some(i => i.src.includes('/media/block-images/') && i.complete && i.naturalWidth > 0));
await page.screenshot({ path: new URL('copied-image-desktop.png', privateDir).pathname, fullPage: true, animations: 'disabled' });
await page.setViewportSize({ width: 390, height: 844 });
assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile layout has no horizontal overflow');
await page.screenshot({ path: new URL('copied-image-mobile.png', privateDir).pathname, fullPage: true, animations: 'disabled' });
await page.setViewportSize({ width: 1280, height: 900 });
await page.goto(session.base + '/dashboard?date=1998-02-01');
const input = page.getByPlaceholder('今、思い出したことを書く…');
await input.waitFor();
const marker = '架空の隔離環境UI検証 ' + Date.now();
await input.fill(marker);
const uploadBytes = await page.evaluate(() => {
  const canvas = document.createElement('canvas'); canvas.width = 8; canvas.height = 8;
  const context = canvas.getContext('2d'); context.fillStyle = '#355ad9'; context.fillRect(0,0,8,8);
  return canvas.toDataURL('image/png').split(',')[1];
});
await page.locator('input[type="file"]').first().setInputFiles({ name: 'synthetic-ui.png', mimeType: 'image/png', buffer: Buffer.from(uploadBytes, 'base64') });
await page.getByRole('button', { name: '次へ', exact: true }).click();
const writeResponse = page.waitForResponse(response => response.url() === session.base + '/api/data/blocks' && response.request().method() === 'POST' && response.request().postDataJSON()?.action === 'insert');
await page.getByRole('button', { name: '保存', exact: true }).click();
const savedResponse = await writeResponse;
assert.ok(savedResponse.ok(), 'Synthetic UI save request succeeds');
const saved = await savedResponse.json();
assert.equal(saved.data?.content, marker, 'Worker persisted the synthetic UI text');
const savedId = saved.data.id;
assert.equal(saved.data.images.length, 1, 'UI image upload was persisted');
assert.ok(saved.data.images[0].startsWith(session.base + '/media/block-images/'), 'UI image goes to isolated R2');
await page.getByText(marker, { exact: true }).first().waitFor();
await page.reload();
await page.getByText(marker, { exact: true }).first().waitFor();
// Inspect and remove only this synthetic record through the same owner API.
const cleanup = await page.evaluate(async savedId => {
  const call = async (table, body) => (await fetch('/api/data/' + table, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })).json();
  const rows = await call('blocks', { action: 'select', filters: [{ column: 'id', op: 'eq', value: savedId }] });
  if (rows.data?.length !== 1) return false;
  const row = rows.data[0];
  await call('blocks', { action: 'delete', filters: [{ column: 'id', op: 'eq', value: row.id }] });
  await call('entries', { action: 'delete', filters: [{ column: 'id', op: 'eq', value: row.entry_id }] });
  const deleted = await fetch('/api/images/delete', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ paths: row.images.map(url => url.split('/media/block-images/')[1]) }) });
  if (!deleted.ok) return false;
  return true;
}, savedId);
assert.ok(cleanup, 'Only the synthetic UI record was saved, reloaded and removed');
assert.deepEqual(errors, [], 'No browser runtime exceptions');
assert.deepEqual(externalRequests, [], 'No request to the production backend or any external service');
assert.deepEqual(failures, [], 'All UI requests succeeded');
await writeFile(new URL('full-ui-verification.json', privateDir), JSON.stringify({ at: new Date().toISOString(), ownerLogin: 'operator-session; owner password unchanged', copiedRecordDisplay: true, copiedImageDisplay: true, syntheticSaveReloadCleanup: true, imageUpload: true, desktop: true, mobile: true, errors, externalRequests, failures }, null, 2), { mode: 0o600 });
await browser.close();
console.log('Browser verification passed: owner login, copied records/images, synthetic save/reload, desktop/mobile, no external requests.');
